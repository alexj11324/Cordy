fn classify_retry_reason(
    result: &ProtocolOutcome,
    stderr: &str,
    cleanup_confirmed: bool,
) -> RetryReason {
    if !cleanup_confirmed {
        return RetryReason::None;
    }
    if is_initialize_timeout(&result.error) {
        return RetryReason::Initialize;
    }
    if result.status == "timeout"
        && result
            .error
            .starts_with(CODEX_FIRST_TURN_NO_PROGRESS_MARKER)
        && classify_codex_startup_stderr(stderr, true).model_refresh_failure > 0
    {
        RetryReason::ModelCatalogRefresh
    } else {
        RetryReason::None
    }
}

fn retry_backoff(reason: RetryReason) -> Duration {
    match reason {
        RetryReason::Initialize => INITIALIZE_RETRY_BACKOFF,
        RetryReason::ModelCatalogRefresh => {
            let jitter_ms = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map(|duration| u64::from(duration.subsec_millis()))
                .unwrap_or_default();
            MODEL_CATALOG_RETRY_BACKOFF + Duration::from_millis(jitter_ms)
        }
        RetryReason::None => Duration::ZERO,
    }
}

fn reset_resume_for_model_catalog_retry(options: &mut ExecOptions) {
    if options.resume_session_id.is_empty() {
        return;
    }
    options.resume_session_id.clear();
    options.resume_expected = true;
}

fn number(object: &Map<String, Value>, keys: &[&str]) -> i64 {
    for key in keys {
        let Some(value) = object.get(*key) else {
            continue;
        };
        if let Some(value) = value.as_i64() {
            return value;
        }
        if let Some(value) = value.as_u64() {
            return value.try_into().unwrap_or(i64::MAX);
        }
        if let Some(value) = value.as_f64() {
            if value.is_finite() && value > 0.0 {
                return value.min(i64::MAX as f64) as i64;
            }
        }
    }
    0
}

fn extract_thread_id(value: &Value) -> Option<String> {
    value
        .get("thread")
        .and_then(|thread| thread.get("id"))
        .and_then(Value::as_str)
        .or_else(|| value.get("threadId").and_then(Value::as_str))
        .or_else(|| value.get("id").and_then(Value::as_str))
        .map(str::to_string)
        .filter(|id| !id.is_empty())
}

fn extract_model(value: &Value) -> Option<String> {
    value
        .get("model")
        .and_then(Value::as_str)
        .or_else(|| {
            value
                .get("thread")
                .and_then(|thread| thread.get("model"))
                .and_then(Value::as_str)
        })
        .map(str::to_string)
        .filter(|model| !model.is_empty())
}

fn nested_string<'a>(value: &'a Value, keys: &[&str]) -> Option<&'a str> {
    let mut current = value;
    for key in keys {
        current = current.get(*key)?;
    }
    current.as_str()
}

