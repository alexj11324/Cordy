async fn detect_codex_version_for_diagnostics(
    command_path: &str,
    prefix: &[String],
    env: &BTreeMap<String, String>,
) -> String {
    let mut command = Command::new(command_path);
    command
        .args(prefix)
        .arg("--version")
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .envs(env)
        .kill_on_drop(false);
    let mut tree = match OwnedProcessTree::spawn(&mut command).await {
        Ok(tree) => tree,
        Err(_) => return "unknown".to_string(),
    };
    let Some(stdout) = tree.child_mut().stdout.take() else {
        let _ = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;
        return "unknown".to_string();
    };
    let Some(stderr) = tree.child_mut().stderr.take() else {
        let _ = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;
        return "unknown".to_string();
    };
    let mut stdout_task = tokio::spawn(read_bounded_diagnostic(stdout));
    let mut stderr_task = tokio::spawn(read_bounded_diagnostic(stderr));
    let success = tokio::time::timeout(CODEX_VERSION_DIAGNOSTIC_TIMEOUT, tree.wait())
        .await
        .ok()
        .and_then(Result::ok)
        .is_some_and(|status| status.success());
    let _ = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;
    if !success {
        stdout_task.abort();
        stderr_task.abort();
        return "unknown".to_string();
    }
    let mut data = tokio::time::timeout(KILL_GRACE, &mut stdout_task)
        .await
        .ok()
        .and_then(Result::ok)
        .and_then(Result::ok)
        .unwrap_or_default();
    data.extend(
        tokio::time::timeout(KILL_GRACE, &mut stderr_task)
            .await
            .ok()
            .and_then(Result::ok)
            .and_then(Result::ok)
            .unwrap_or_default(),
    );
    if !stdout_task.is_finished() {
        stdout_task.abort();
    }
    if !stderr_task.is_finished() {
        stderr_task.abort();
    }
    let version = extract_version_line(&String::from_utf8_lossy(&data));
    if version.trim().is_empty() {
        "unknown".to_string()
    } else {
        version
    }
}

async fn read_bounded_diagnostic<R>(reader: R) -> io::Result<Vec<u8>>
where
    R: tokio::io::AsyncRead + Unpin,
{
    let mut output = Vec::new();
    reader
        .take(CODEX_VERSION_DIAGNOSTIC_OUTPUT_MAX as u64)
        .read_to_end(&mut output)
        .await?;
    Ok(output)
}

fn describe_message_activity(message: &Message) -> String {
    match message.message_type {
        MessageType::Text => "text".to_string(),
        MessageType::Thinking => "thinking".to_string(),
        MessageType::ToolUse => {
            if message.tool.is_empty() {
                "tool-use".to_string()
            } else {
                format!("tool-use:{}", message.tool)
            }
        }
        MessageType::ToolResult => {
            if message.tool.is_empty() {
                "tool-result".to_string()
            } else {
                format!("tool-result:{}", message.tool)
            }
        }
        MessageType::Status => {
            if message.status.is_empty() {
                "status".to_string()
            } else {
                format!("status:{}", message.status)
            }
        }
        MessageType::Error => "error".to_string(),
        MessageType::Log => "log".to_string(),
    }
}

fn describe_item_activity(method: &str, item_type: &str, item_id: &str) -> String {
    let item_type = if item_type.is_empty() {
        "unknown"
    } else {
        item_type
    };
    if item_id.is_empty() {
        format!("{method}:{item_type}")
    } else {
        format!("{method}:{item_type}:{item_id}")
    }
}

impl CodexState {
    fn start_first_item_wait(&mut self) {
        if self.first_item_wait_started.is_none() {
            self.first_item_wait_started = Some(Instant::now());
        }
    }

    fn finish_first_item_wait(&mut self, outcome: &str) {
        if self.first_item_wait_started.is_none() || !self.first_item_wait_outcome.is_empty() {
            return;
        }
        self.first_item_wait_finished = Some(Instant::now());
        self.first_item_wait_outcome = outcome.to_string();
    }

    fn first_item_wait_snapshot(
        &self,
        timeout: Duration,
        semantic_inactivity_timeout: Duration,
    ) -> Option<CodexFirstItemWaitObservation> {
        let started = self.first_item_wait_started?;
        let finished = self.first_item_wait_finished?;
        if self.first_item_wait_outcome.is_empty() {
            return None;
        }
        Some(CodexFirstItemWaitObservation {
            latency: finished.saturating_duration_since(started),
            outcome: self.first_item_wait_outcome.clone(),
            thread_id: self.thread_id.clone(),
            turn_id: self.turn_id.clone(),
            timeout,
            semantic_inactivity_timeout,
            attempt_number: self.attempt_number,
            stderr_classification: self.first_item_wait_stderr_classification,
        })
    }

    fn set_error(&mut self, error: &str) {
        if self.turn_error.is_empty() && !error.is_empty() {
            self.turn_error = error.to_string();
        }
    }

    fn merge_usage(&mut self, value: Option<&Value>) {
        let Some(value) = value else {
            return;
        };
        let usage = value
            .get("usage")
            .or_else(|| value.get("token_usage"))
            .or_else(|| value.get("tokens"))
            .unwrap_or(value);
        let Some(usage) = usage.as_object() else {
            return;
        };
        let input = number(usage, &["input_tokens", "input", "prompt_tokens"]);
        let cached = number(
            usage,
            &[
                "cached_input_tokens",
                "cache_read_tokens",
                "cache_read_input_tokens",
            ],
        );
        let parsed = TokenUsage {
            input_tokens: input.saturating_sub(cached).max(0),
            output_tokens: number(usage, &["output_tokens", "output", "completion_tokens"])
                .saturating_add(number(usage, &["reasoning_output_tokens"])),
            cache_read_tokens: cached,
            cache_write_tokens: number(
                usage,
                &["cache_write_tokens", "cache_creation_input_tokens"],
            ),
            cost_usd_ticks: number(usage, &["cost_usd_ticks"]),
        };
        self.usage.input_tokens = self.usage.input_tokens.max(parsed.input_tokens);
        self.usage.output_tokens = self.usage.output_tokens.max(parsed.output_tokens);
        self.usage.cache_read_tokens = self.usage.cache_read_tokens.max(parsed.cache_read_tokens);
        self.usage.cache_write_tokens =
            self.usage.cache_write_tokens.max(parsed.cache_write_tokens);
        self.usage.cost_usd_ticks = self.usage.cost_usd_ticks.max(parsed.cost_usd_ticks);
    }
}

