    #[tokio::test]
    async fn retry_wrapper_flushes_held_status_before_result() {
        let (attempt_message_tx, attempt_message_rx) = mpsc::channel(4);
        let (attempt_result_tx, attempt_result_rx) = oneshot::channel();
        let (retry_tx, retry_rx) = oneshot::channel();
        let attempt = CodexAttempt {
            session: Session {
                messages: attempt_message_rx,
                result: attempt_result_rx,
            },
            retry_reason: retry_rx,
        };
        let (message_tx, mut message_rx) = mpsc::channel(4);
        let (result_tx, result_rx) = oneshot::channel();
        let task = tokio::spawn(run_codex_attempts(
            CodexBackend::new(CodexConfig::default()),
            "prompt".to_string(),
            ExecOptions::default(),
            attempt,
            message_tx,
            result_tx,
            CancellationToken::new(),
        ));

        attempt_message_tx
            .send(status_message("running", "thread-1"))
            .await
            .unwrap_or_else(|error| panic!("send running status: {error}"));
        attempt_message_tx
            .send(message(MessageType::Text, "done"))
            .await
            .unwrap_or_else(|error| panic!("send final message: {error}"));
        drop(attempt_message_tx);
        retry_tx
            .send(RetryReason::None)
            .unwrap_or_else(|_| panic!("send retry decision"));
        attempt_result_tx
            .send(ExecutionResult {
                status: "completed".to_string(),
                output: "done".to_string(),
                ..ExecutionResult::default()
            })
            .unwrap_or_else(|_| panic!("send attempt result"));

        task.await
            .unwrap_or_else(|error| panic!("join retry wrapper: {error}"));
        let first = message_rx
            .recv()
            .await
            .unwrap_or_else(|| panic!("running status message"));
        let second = message_rx
            .recv()
            .await
            .unwrap_or_else(|| panic!("text message"));
        assert_eq!(first.message_type, MessageType::Status);
        assert_eq!(first.status, "running");
        assert_eq!(second.message_type, MessageType::Text);
        assert_eq!(second.content, "done");
        assert_eq!(
            result_rx
                .await
                .unwrap_or_else(|error| panic!("receive result: {error}"))
                .status,
            "completed"
        );
    }

