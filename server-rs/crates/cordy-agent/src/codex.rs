/// Builds the daemon-owned Codex app-server invocation.
pub fn build_codex_args(options: &ExecOptions) -> Vec<String> {
    let mut args = vec![
        "app-server".to_string(),
        "--listen".to_string(),
        "stdio://".to_string(),
    ];
    let managed_mcp = crate::mcp::has_managed_config(options.mcp_config.as_ref());
    let extra = filter_custom_args(&options.extra_args, &BLOCKED_ARGS).args;
    let custom = filter_custom_args(&options.custom_args, &BLOCKED_ARGS).args;
    if managed_mcp {
        args.extend(filter_managed_mcp_overrides(extra));
        args.extend(filter_managed_mcp_overrides(custom));
    } else {
        args.extend(extra);
        args.extend(custom);
    }
    if options.service_tier == "priority" {
        args = strip_fast_mode_conflicts(args);
        args.extend(["--enable".to_string(), "fast_mode".to_string()]);
    }
    args
}

fn strip_fast_mode_conflicts(args: Vec<String>) -> Vec<String> {
    let mut filtered = Vec::with_capacity(args.len());
    let mut index = 0;
    while index < args.len() {
        let arg = args[index].as_str();
        if arg == "--disable=fast_mode" {
            index += 1;
            continue;
        }
        if arg == "--disable"
            && args
                .get(index + 1)
                .is_some_and(|value| value == "fast_mode")
        {
            index += 2;
            continue;
        }
        if (arg == "-c" || arg == "--config")
            && args
                .get(index + 1)
                .is_some_and(|value| value.starts_with("features.fast_mode"))
        {
            index += 2;
            continue;
        }
        if (arg.starts_with("-c=") || arg.starts_with("--config="))
            && arg
                .split_once('=')
                .is_some_and(|(_, value)| value.starts_with("features.fast_mode"))
        {
            index += 1;
            continue;
        }
        filtered.push(args[index].clone());
        index += 1;
    }
    filtered
}

fn filter_managed_mcp_overrides(args: Vec<String>) -> Vec<String> {
    let mut filtered = Vec::with_capacity(args.len());
    let mut index = 0;
    while index < args.len() {
        let argument = &args[index];
        let (flag, inline_value) = argument
            .split_once('=')
            .map_or((argument.as_str(), None), |(flag, value)| {
                (flag, Some(value))
            });
        if matches!(flag, "-c" | "--config") {
            let value = inline_value.or_else(|| args.get(index + 1).map(String::as_str));
            if value.is_some_and(is_mcp_config_key) {
                index += 1 + usize::from(inline_value.is_none() && index + 1 < args.len());
                continue;
            }
        }
        filtered.push(argument.clone());
        index += 1;
    }
    filtered
}

fn is_mcp_config_key(value: &str) -> bool {
    let value = value.trim();
    let Some(rest) = value.strip_prefix("mcp_servers") else {
        return false;
    };
    let rest = rest.trim_start();
    rest.is_empty() || rest.starts_with('.') || rest.starts_with('=')
}

fn ensure_codex_mcp_config(path: &Path, config: Option<&Value>) -> Result<(), AgentError> {
    let existing = match fs::read_to_string(path) {
        Ok(value) => value,
        Err(error) if error.kind() == io::ErrorKind::NotFound => String::new(),
        Err(error) => return Err(AgentError::Process(error)),
    };
    let mut stripped = strip_codex_managed_block(&existing);
    let managed = crate::mcp::has_managed_config(config);
    let updated = if managed {
        stripped = strip_codex_user_mcp_tables(&stripped);
        let block = render_codex_mcp_servers_block(config)?;
        let block = if block.is_empty() {
            format!("{CODEX_MCP_BEGIN}\n{CODEX_MCP_END}\n")
        } else {
            block
        };
        let prefix = stripped.trim_end();
        if prefix.is_empty() {
            block
        } else {
            format!("{prefix}\n\n{block}")
        }
    } else {
        stripped
    };
    if updated == existing {
        return Ok(());
    }
    write_private_codex_config(path, &updated).map_err(AgentError::Process)?;
    Ok(())
}

fn write_private_codex_config(path: &Path, content: &str) -> io::Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::{OpenOptionsExt, PermissionsExt};

        // Open without truncating first so an existing 0644 file is tightened
        // before any managed MCP credentials are written into it.
        let mut options = fs::OpenOptions::new();
        options.create(true).write(true).mode(0o600);
        let mut file = options.open(path)?;
        file.set_permissions(fs::Permissions::from_mode(0o600))?;
        file.set_len(0)?;
        file.write_all(content.as_bytes())?;
        file.flush()?;
        // Keep the final chmod as defense in depth if another local process
        // changed the mode while the file was being regenerated.
        file.set_permissions(fs::Permissions::from_mode(0o600))?;
        Ok(())
    }

    #[cfg(not(unix))]
    {
        fs::write(path, content)
    }
}

fn strip_codex_managed_block(content: &str) -> String {
    let mut output = Vec::new();
    let mut skipping = false;
    for line in content.split('\n') {
        let trimmed = line.trim();
        if trimmed == CODEX_MCP_BEGIN {
            skipping = true;
            continue;
        }
        if skipping {
            if trimmed == CODEX_MCP_END {
                skipping = false;
            }
            continue;
        }
        output.push(line);
    }
    output.join("\n")
}

fn strip_codex_user_mcp_tables(content: &str) -> String {
    let mut output = Vec::new();
    let mut skipping = false;
    for line in content.split('\n') {
        let trimmed = line.trim();
        if is_codex_mcp_table_header(trimmed) {
            skipping = true;
            continue;
        }
        if skipping {
            if trimmed.starts_with('[') {
                if is_codex_mcp_table_header(trimmed) {
                    continue;
                }
                skipping = false;
                output.push(line);
            }
            continue;
        }
        output.push(line);
    }
    output.join("\n")
}

fn is_codex_mcp_table_header(line: &str) -> bool {
    let Some(inner) = line
        .trim()
        .strip_prefix('[')
        .and_then(|line| line.strip_suffix(']'))
    else {
        return false;
    };
    let Some(rest) = inner.trim().strip_prefix("mcp_servers") else {
        return false;
    };
    rest.trim_start().starts_with('.')
}

fn render_codex_mcp_servers_block(config: Option<&Value>) -> Result<String, AgentError> {
    let Some(config) = config.filter(|value| !value.is_null()) else {
        return Ok(String::new());
    };
    let object = config.as_object().ok_or_else(|| {
        AgentError::InvalidConfig("codex mcp_config must be a JSON object".to_string())
    })?;
    let Some(raw_servers) = object.get("mcpServers") else {
        return Ok(String::new());
    };
    let servers = match raw_servers {
        Value::Null => return Ok(String::new()),
        Value::Object(servers) => servers,
        _ => {
            return Err(AgentError::InvalidConfig(
                "codex mcp_config.mcpServers must be a JSON object".to_string(),
            ));
        }
    };
    if servers.is_empty() {
        return Ok(String::new());
    }

    let mut names: Vec<&str> = servers.keys().map(String::as_str).collect();
    names.sort_unstable();
    let mut output = String::from(CODEX_MCP_BEGIN);
    output.push('\n');
    for name in names {
        if !is_codex_bare_toml_key(name) {
            return Err(AgentError::InvalidConfig(format!(
                "mcp server name {name:?} must contain only ASCII letters, numbers, _ or -"
            )));
        }
        let server = servers
            .get(name)
            .and_then(Value::as_object)
            .ok_or_else(|| {
                AgentError::InvalidConfig(format!("codex mcp_servers.{name} must be a JSON object"))
            })?;
        let server = normalize_codex_mcp_server(server);
        output.push_str("[mcp_servers.");
        output.push_str(name);
        output.push_str("]\n");
        let mut keys: Vec<&str> = server.keys().map(String::as_str).collect();
        keys.sort_unstable();
        for key in keys {
            let value = json_value_to_codex_toml(
                server
                    .get(key)
                    .ok_or_else(|| AgentError::InvalidConfig("missing MCP value".to_string()))?,
            )
            .map_err(|error| {
                AgentError::InvalidConfig(format!("mcp_servers.{name}.{key}: {error}"))
            })?;
            output.push_str(&codex_toml_key(key));
            output.push_str(" = ");
            output.push_str(&value);
            output.push('\n');
        }
        output.push('\n');
    }
    output.push_str(CODEX_MCP_END);
    output.push('\n');
    Ok(output)
}

fn normalize_codex_mcp_server(server: &Map<String, Value>) -> Map<String, Value> {
    let remote = server
        .get("type")
        .and_then(Value::as_str)
        .is_some_and(|value| value.eq_ignore_ascii_case("http"))
        || (server.get("url").is_some() && server.get("command").is_none());
    let mut normalized = Map::new();
    for (key, value) in server {
        if matches!(key.as_str(), "tools" | "prompts" | "resources") {
            continue;
        }
        if remote && key == "type" {
            continue;
        }
        if remote && key == "headers" {
            if !server.contains_key("http_headers") {
                normalized.insert("http_headers".to_string(), value.clone());
            }
        } else {
            normalized.insert(key.clone(), value.clone());
        }
    }
    if remote {
        normalized.insert(
            "experimental_use_rmcp_client".to_string(),
            Value::Bool(true),
        );
    }
    normalized
}

fn json_value_to_codex_toml(value: &Value) -> Result<String, String> {
    match value {
        Value::Null => Err("null is not a valid TOML value".to_string()),
        Value::Bool(value) => Ok(value.to_string()),
        Value::Number(value) => Ok(value.to_string()),
        Value::String(value) => Ok(codex_toml_basic_string(value)),
        Value::Array(values) => values
            .iter()
            .map(json_value_to_codex_toml)
            .collect::<Result<Vec<_>, _>>()
            .map(|values| format!("[{}]", values.join(", "))),
        Value::Object(object) => {
            let mut keys: Vec<&str> = object.keys().map(String::as_str).collect();
            keys.sort_unstable();
            let values = keys
                .into_iter()
                .map(|key| {
                    let value = json_value_to_codex_toml(
                        object
                            .get(key)
                            .ok_or_else(|| "missing inline table value".to_string())?,
                    )?;
                    Ok(format!("{} = {value}", codex_toml_key(key)))
                })
                .collect::<Result<Vec<_>, String>>()?;
            Ok(format!("{{ {} }}", values.join(", ")))
        }
    }
}

fn codex_toml_key(value: &str) -> String {
    if is_codex_bare_toml_key(value) {
        value.to_string()
    } else {
        codex_toml_basic_string(value)
    }
}

fn is_codex_bare_toml_key(value: &str) -> bool {
    !value.is_empty()
        && value
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || matches!(character, '_' | '-'))
}

fn codex_toml_basic_string(value: &str) -> String {
    let mut output = String::with_capacity(value.len() + 2);
    output.push('"');
    for character in value.chars() {
        match character {
            '\\' => output.push_str("\\\\"),
            '"' => output.push_str("\\\""),
            '\u{8}' => output.push_str("\\b"),
            '\t' => output.push_str("\\t"),
            '\n' => output.push_str("\\n"),
            '\u{c}' => output.push_str("\\f"),
            '\r' => output.push_str("\\r"),
            character if character.is_control() => {
                output.push_str(&format!("\\u{:04x}", character as u32));
            }
            character => output.push(character),
        }
    }
    output.push('"');
    output
}

#[async_trait]
impl Backend for CodexBackend {
    async fn execute(&self, prompt: &str, options: ExecOptions) -> Result<Session, AgentError> {
        let deadline = (!options.timeout.is_zero())
            .then(|| Instant::now().checked_add(options.timeout))
            .flatten();
        let first_attempt = self.execute_once(prompt, options.clone(), 1).await?;
        let (message_tx, message_rx) = mpsc::channel(MESSAGE_BUFFER);
        let (result_tx, result_rx) = oneshot::channel();
        let backend = self.clone();
        let prompt = prompt.to_string();
        let cancellation = options.cancellation.clone();

        tokio::spawn(async move {
            run_codex_attempts(
                backend,
                prompt,
                options,
                first_attempt,
                message_tx,
                result_tx,
                cancellation,
                deadline,
            )
            .await;
        });

        Ok(Session {
            messages: message_rx,
            result: result_rx,
        })
    }
}

impl CodexBackend {
    async fn execute_once(
        &self,
        prompt: &str,
        options: ExecOptions,
        attempt_number: u8,
    ) -> Result<CodexAttempt, AgentError> {
        let managed_mcp = crate::mcp::has_managed_config(options.mcp_config.as_ref());
        let codex_home = self
            .config
            .env
            .get("CODEX_HOME")
            .map(|value| value.trim())
            .filter(|value| !value.is_empty());
        if managed_mcp && codex_home.is_none() {
            return Err(AgentError::InvalidConfig(
                "codex: mcp_config is set but CODEX_HOME env var is not configured; cannot apply managed MCP"
                    .to_string(),
            ));
        }
        if let Some(codex_home) = codex_home {
            ensure_codex_mcp_config(
                Path::new(codex_home).join("config.toml").as_path(),
                options.mcp_config.as_ref(),
            )?;
        }

        let command_path = if self.config.command.path.trim().is_empty() {
            "codex"
        } else {
            self.config.command.path.as_str()
        };
        let mut prefix = filter_launch_prefix(&self.config.command.prefix, &BLOCKED_ARGS).args;
        if managed_mcp {
            prefix = filter_managed_mcp_overrides(prefix);
        }
        let diagnostic_prefix = prefix.clone();
        let diagnostic_env = self.config.env.clone();
        let diagnostic_command_path = command_path.to_string();
        let mut argv = prefix;
        argv.extend(build_codex_args(&options));

        let mut command = Command::new(command_path);
        command
            .args(&argv)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .envs(&self.config.env)
            .kill_on_drop(false);
        if !options.cwd.is_empty() {
            command.current_dir(&options.cwd);
        }

        let mut tree = OwnedProcessTree::spawn(&mut command)
            .await
            .map_err(|error| {
                if error.kind() == io::ErrorKind::NotFound {
                    AgentError::ExecutableNotFound(command_path.to_string())
                } else {
                    AgentError::Process(error)
                }
            })?;
        let Some(stdin) = tree.child_mut().stdin.take() else {
            let _ = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;
            return Err(AgentError::Protocol(
                "Codex stdin pipe unavailable after spawn".to_string(),
            ));
        };
        let Some(stdout) = tree.child_mut().stdout.take() else {
            let _ = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;
            return Err(AgentError::Protocol(
                "Codex stdout pipe unavailable after spawn".to_string(),
            ));
        };
        let Some(stderr) = tree.child_mut().stderr.take() else {
            let _ = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;
            return Err(AgentError::Protocol(
                "Codex stderr pipe unavailable after spawn".to_string(),
            ));
        };

        let (message_tx, message_rx) = mpsc::channel(MESSAGE_BUFFER);
        let (result_tx, result_rx) = oneshot::channel();
        let (retry_tx, retry_rx) = oneshot::channel();
        let timeout = options.timeout;
        let cancellation = options.cancellation.clone();
        let configured_model = options.model.clone();
        let codex_home = self.config.env.get("CODEX_HOME").cloned();
        let started = Instant::now();
        let started_at = SystemTime::now();
        let prompt = prompt.to_string();
        let stderr_tail = SharedDiagnosticBuffer::new(DEFAULT_TAIL_BYTES);
        let stderr_reader_tail = stderr_tail.clone();

        tokio::spawn(async move {
            run_codex(
                tree,
                stdin,
                stdout,
                stderr,
                prompt,
                options,
                message_tx,
                result_tx,
                retry_tx,
                cancellation,
                timeout,
                configured_model,
                codex_home,
                diagnostic_command_path,
                diagnostic_prefix,
                diagnostic_env,
                started,
                started_at,
                stderr_tail,
                stderr_reader_tail,
                attempt_number,
            )
            .await;
        });

        Ok(CodexAttempt {
            session: Session {
                messages: message_rx,
                result: result_rx,
            },
            retry_reason: retry_rx,
        })
    }
}

#[allow(clippy::too_many_arguments)]
async fn run_codex_attempts(
    backend: CodexBackend,
    prompt: String,
    options: ExecOptions,
    attempt: CodexAttempt,
    messages: mpsc::Sender<Message>,
    result_tx: oneshot::Sender<ExecutionResult>,
    cancellation: CancellationToken,
    deadline: Option<Instant>,
) {
    let mut attempt = Some(attempt);
    let mut attempt_options = options;
    for attempt_number in 1..=2 {
        if attempt_number > 1 {
            if let Some(deadline) = deadline {
                let remaining = deadline.saturating_duration_since(Instant::now());
                if remaining.is_zero() {
                    let _ = result_tx.send(ExecutionResult {
                        status: "timeout".to_string(),
                        error: "codex retry budget expired".to_string(),
                        ..ExecutionResult::default()
                    });
                    return;
                }
                attempt_options.timeout = remaining;
                let handshake_timeout = if attempt_options.handshake_timeout.is_zero() {
                    DEFAULT_HANDSHAKE_TIMEOUT
                } else {
                    attempt_options.handshake_timeout
                };
                attempt_options.handshake_timeout = handshake_timeout.min(remaining);
            }
            attempt = Some(
                match backend
                    .execute_once(&prompt, attempt_options.clone(), attempt_number)
                    .await
                {
                    Ok(attempt) => attempt,
                    Err(error) => {
                        let _ = result_tx.send(ExecutionResult {
                            status: "failed".to_string(),
                            error: error.to_string(),
                            ..ExecutionResult::default()
                        });
                        return;
                    }
                },
            );
        }

        let Some(CodexAttempt {
            session,
            retry_reason,
        }) = attempt.take()
        else {
            return;
        };
        let Session {
            messages: mut attempt_messages,
            result: attempt_result,
        } = session;
        let mut held = Vec::new();
        let mut holding = true;
        while let Some(message) = attempt_messages.recv().await {
            if holding && message.message_type == MessageType::Status && message.status == "running"
            {
                held.push(message);
                continue;
            }
            if holding {
                for held_message in held.drain(..) {
                    if messages.send(held_message).await.is_err() {
                        return;
                    }
                }
                holding = false;
            }
            if messages.send(message).await.is_err() {
                return;
            }
        }

        let result = match attempt_result.await {
            Ok(result) => result,
            Err(_) => {
                let _ = result_tx.send(ExecutionResult {
                    status: "failed".to_string(),
                    error: "codex attempt closed without result".to_string(),
                    ..ExecutionResult::default()
                });
                return;
            }
        };
        let retry_reason = retry_reason.await.unwrap_or_default();
        if retry_reason == RetryReason::None || attempt_number == 2 {
            for held_message in held {
                if messages.send(held_message).await.is_err() {
                    return;
                }
            }
            let _ = result_tx.send(result);
            return;
        }

        if retry_reason == RetryReason::ModelCatalogRefresh {
            reset_resume_for_model_catalog_retry(&mut attempt_options);
        }
        let retry_delay = retry_backoff(retry_reason);
        if let Some(deadline) = deadline {
            let remaining = deadline.saturating_duration_since(Instant::now());
            if remaining <= retry_delay {
                for held_message in held {
                    if messages.send(held_message).await.is_err() {
                        return;
                    }
                }
                let _ = result_tx.send(result);
                return;
            }
        }
        let retry = tokio::time::sleep(retry_delay);
        tokio::pin!(retry);
        tokio::select! {
            () = cancellation.cancelled() => {
                for held_message in held {
                    if messages.send(held_message).await.is_err() {
                        return;
                    }
                }
                let _ = result_tx.send(result);
                return;
            }
            () = &mut retry => {}
        }
    }
}

#[allow(clippy::too_many_arguments)]
async fn run_codex(
    mut tree: OwnedProcessTree,
    stdin: ChildStdin,
    stdout: ChildStdout,
    stderr: ChildStderr,
    prompt: String,
    options: ExecOptions,
    messages: mpsc::Sender<Message>,
    result_tx: oneshot::Sender<ExecutionResult>,
    retry_tx: oneshot::Sender<RetryReason>,
    cancellation: CancellationToken,
    timeout: Duration,
    configured_model: String,
    codex_home: Option<String>,
    diagnostic_command_path: String,
    diagnostic_prefix: Vec<String>,
    diagnostic_env: BTreeMap<String, String>,
    started: Instant,
    started_at: SystemTime,
    stderr_tail: SharedDiagnosticBuffer,
    stderr_reader_tail: SharedDiagnosticBuffer,
    attempt_number: u8,
) {
    let mut stderr_task = tokio::spawn(pump_stderr(stderr, stderr_reader_tail));
    let handshake_timeout = if options.handshake_timeout.is_zero() {
        DEFAULT_HANDSHAKE_TIMEOUT
    } else {
        options.handshake_timeout
    };
    let live_protocol = Arc::new(Mutex::new(CodexLiveProtocol {
        attempt_number,
        ..CodexLiveProtocol::default()
    }));
    let mut protocol = Box::pin(run_protocol(
        stdin,
        stdout,
        prompt,
        options,
        messages,
        handshake_timeout,
        live_protocol.clone(),
        stderr_tail.clone(),
    ));

    let outcome = if timeout.is_zero() {
        tokio::select! {
            result = &mut protocol => RunOutcome::Protocol(Box::new(result)),
            () = cancellation.cancelled() => RunOutcome::Cancelled,
        }
    } else {
        tokio::select! {
            result = &mut protocol => RunOutcome::Protocol(Box::new(result)),
            () = cancellation.cancelled() => RunOutcome::Cancelled,
            () = tokio::time::sleep(timeout) => RunOutcome::TimedOut,
        }
    };

    let mut result = match outcome {
        RunOutcome::Protocol(result) => *result,
        RunOutcome::Cancelled => terminal_outcome_from_live(
            "aborted",
            "execution cancelled",
            "cancelled",
            &live_protocol,
            &stderr_tail,
            &configured_model,
        ),
        RunOutcome::TimedOut => terminal_outcome_from_live(
            "timeout",
            format!("codex timed out after {}s", timeout.as_secs_f64()),
            "execution_timeout",
            &live_protocol,
            &stderr_tail,
            &configured_model,
        ),
    };
    let cleanup_confirmed = tree.shutdown(TERMINATION_GRACE, KILL_GRACE).await;

    if tokio::time::timeout(KILL_GRACE, &mut stderr_task)
        .await
        .is_err()
    {
        stderr_task.abort();
    }
    let stderr = stderr_tail.tail();
    let has_timeout_diagnostic = result.timeout_diagnostic.is_some();
    if let Some(mut diagnostic) = result.timeout_diagnostic.take() {
        diagnostic.codex_version = detect_codex_version_for_diagnostics(
            &diagnostic_command_path,
            &diagnostic_prefix,
            &diagnostic_env,
        )
        .await;
        result.error = build_codex_timeout_diagnostic_error(&diagnostic, &stderr);
    }
    let retry_reason = classify_retry_reason(&result, &stderr, cleanup_confirmed);
    let _ = retry_tx.send(retry_reason);
    if let Some(observation) = result.first_item_wait.take() {
        let classification = if observation.outcome.ends_with("_timeout") {
            classify_codex_startup_stderr(&stderr, true)
        } else {
            observation.stderr_classification
        };
        let retry_safe = retry_reason == RetryReason::ModelCatalogRefresh;
        let latency_ms = observation
            .latency
            .as_millis()
            .try_into()
            .unwrap_or(i64::MAX);
        let timeout_ms = observation
            .timeout
            .as_millis()
            .try_into()
            .unwrap_or(i64::MAX);
        let semantic_inactivity_timeout_ms = observation
            .semantic_inactivity_timeout
            .as_millis()
            .try_into()
            .unwrap_or(i64::MAX);
        macro_rules! log_first_item_wait {
            ($level:path) => {
                tracing::event!(
                    $level,
                    provider = "codex",
                    phase = "first_item_wait",
                    attempt_number = observation.attempt_number,
                    latency_ms = latency_ms,
                    timeout_ms = timeout_ms,
                    semantic_inactivity_timeout_ms = semantic_inactivity_timeout_ms,
                    thread_id = %observation.thread_id,
                    turn_id = %observation.turn_id,
                    outcome = %observation.outcome,
                    retry_safe = retry_safe,
                    cleanup_confirmed = cleanup_confirmed,
                    reaped = cleanup_confirmed,
                    stderr_model_refresh_failure_count = classification.model_refresh_failure,
                    stderr_model_refresh_timeout_count = classification.model_refresh_timeout,
                    stderr_mcp_init_transport_count = classification.mcp_init_transport,
                    stderr_bare_timeout_count = classification.bare_timeout,
                    "codex lifecycle"
                );
            };
        }
        match observation.outcome.as_str() {
            "progress" | "turn_completed" => {
                log_first_item_wait!(tracing::Level::INFO);
            }
            _ => {
                log_first_item_wait!(tracing::Level::WARN);
            }
        }
    }
    let actual_resumed = result.resumed;
    if !has_usage(&result.usage) && !result.session_id.is_empty() {
        if let Some(scanned) = scan_codex_session_usage(
            codex_home.as_deref(),
            &result.session_id,
            started_at,
            actual_resumed,
        ) {
            let model = if configured_model.is_empty() {
                if scanned.model.is_empty() {
                    "unknown".to_string()
                } else {
                    scanned.model
                }
            } else {
                configured_model
            };
            // Rollout usage is the authoritative fallback. Replace any
            // cache-only RPC bucket atomically so the same turn is not
            // double-counted under two model keys.
            result.usage = BTreeMap::from([(model, scanned.usage)]);
        }
    }
    if !has_timeout_diagnostic && !result.error.is_empty() {
        result.error = with_stderr(&result.error, "codex", &stderr);
    }
    let _ = result_tx.send(ExecutionResult {
        status: result.status,
        output: result.output,
        error: result.error,
        duration_ms: started.elapsed().as_millis().try_into().unwrap_or(i64::MAX),
        session_id: result.session_id,
        usage: result.usage,
        resume_rejected: result.resume_rejected,
    });
}

enum RunOutcome {
    Protocol(Box<ProtocolOutcome>),
    Cancelled,
    TimedOut,
}

#[derive(Debug, Default)]
struct ProtocolOutcome {
    status: String,
    output: String,
    error: String,
    session_id: String,
    usage: BTreeMap<String, TokenUsage>,
    resumed: bool,
    resume_rejected: bool,
    timeout_diagnostic: Option<CodexTimeoutDiagnostic>,
    first_item_wait: Option<CodexFirstItemWaitObservation>,
}

impl ProtocolOutcome {
    fn terminal(status: &str, error: impl Into<String>) -> Self {
        Self {
            status: status.to_string(),
            error: error.into(),
            ..Self::default()
        }
    }

    fn failed(error: impl Into<String>) -> Self {
        Self::terminal("failed", error)
    }
}

fn terminal_outcome_from_live(
    status: &str,
    error: impl Into<String>,
    first_item_outcome: &str,
    live_protocol: &Arc<Mutex<CodexLiveProtocol>>,
    stderr: &SharedDiagnosticBuffer,
    selected_model: &str,
) -> ProtocolOutcome {
    let mut live = live_protocol
        .lock()
        .map(|live| live.clone())
        .unwrap_or_default();
    if live.state.first_item_wait_started.is_some() && live.state.first_item_wait_outcome.is_empty()
    {
        live.state.finish_first_item_wait(first_item_outcome);
        live.state.first_item_wait_stderr_classification =
            classify_codex_startup_stderr(&stderr.tail(), first_item_outcome.ends_with("_timeout"));
    }
    let first_item_wait = live
        .state
        .first_item_wait_snapshot(live.first_turn_timeout, live.semantic_inactivity_timeout);
    let model = if selected_model.is_empty() {
        configured_model(&live.state, &ExecOptions::default())
    } else {
        selected_model.to_string()
    };
    ProtocolOutcome {
        status: status.to_string(),
        error: error.into(),
        output: if !live.state.final_answer.is_empty() {
            live.state.final_answer.clone()
        } else {
            live.state.last_agent_message.clone()
        },
        session_id: live.state.thread_id.clone(),
        usage: usage_map(&live.state, &model),
        resumed: live.resumed,
        resume_rejected: live.resume_rejected,
        first_item_wait,
        ..ProtocolOutcome::default()
    }
}

#[allow(clippy::too_many_arguments)]
async fn run_protocol(
    stdin: ChildStdin,
    stdout: ChildStdout,
    prompt: String,
    options: ExecOptions,
    messages: mpsc::Sender<Message>,
    handshake_timeout: Duration,
    live_protocol: Arc<Mutex<CodexLiveProtocol>>,
    startup_stderr: SharedDiagnosticBuffer,
) -> ProtocolOutcome {
    let attempt_number = live_protocol
        .lock()
        .map(|live| live.attempt_number)
        .unwrap_or(1);
    let mut client = CodexClient::new(BufReader::new(stdout), stdin, messages)
        .with_live_protocol(live_protocol, startup_stderr);
    client.state.attempt_number = attempt_number;
    client.publish_live_state();
    if let Err(error) = client
        .request(
            "initialize",
            serde_json::json!({
                "clientInfo": {
                    "name": "cordy-agent-sdk",
                    "title": "Cordy Agent SDK",
                    "version": "0.2.0"
                },
                "capabilities": {"experimentalApi": true}
            }),
            handshake_timeout,
        )
        .await
    {
        return ProtocolOutcome::failed(error);
    }
    if let Err(error) = client.notify("initialized").await {
        return ProtocolOutcome::failed(format!("codex initialized notification failed: {error}"));
    }

    let cwd = if options.cwd.is_empty() {
        "."
    } else {
        options.cwd.as_str()
    };
    let mut resume_rejected = false;
    let (thread_id, resumed, thread_value) = if options.resume_session_id.is_empty() {
        match start_thread(&mut client, &options, cwd, handshake_timeout).await {
            Ok(value) => value,
            Err(error) => return ProtocolOutcome::failed(error),
        }
    } else {
        let mut resume_params = serde_json::json!({
            "threadId": options.resume_session_id.clone(),
            "cwd": cwd,
            "model": null,
            "developerInstructions": null,
        });
        apply_reasoning_effort(&mut resume_params, &options.thinking_level, false);
        apply_service_tier(&mut resume_params, &options.service_tier);
        match client
            .request("thread/resume", resume_params, handshake_timeout)
            .await
        {
            Ok(value) => {
                if let Some(thread_id) = extract_thread_id(&value) {
                    (thread_id, true, value)
                } else {
                    resume_rejected = true;
                    match start_thread(&mut client, &options, cwd, handshake_timeout).await {
                        Ok(value) => value,
                        Err(error) => return ProtocolOutcome::failed(error),
                    }
                }
            }
            Err(error) if is_codex_resume_overflow(&error) => {
                return ProtocolOutcome {
                    status: "failed".to_string(),
                    error: format!(
                        "{CODEX_RESUME_FAILURE_MARKER}: {CODEX_RESUME_OVERFLOW_MARKER} ({error})"
                    ),
                    resume_rejected: true,
                    ..ProtocolOutcome::default()
                };
            }
            Err(error) if !is_transport_error(&error) => {
                resume_rejected = true;
                match start_thread(&mut client, &options, cwd, handshake_timeout).await {
                    Ok(value) => value,
                    Err(start_error) => {
                        return ProtocolOutcome::failed(format!(
                            "{error}; fresh Codex thread/start failed: {start_error}"
                        ));
                    }
                }
            }
            Err(error) => return ProtocolOutcome::failed(error),
        }
    };

    let semantic_timeout =
        resolved_semantic_inactivity_timeout(options.semantic_inactivity_timeout);
    let first_turn_timeout =
        first_turn_no_progress_timeout(semantic_timeout, options.first_turn_no_progress_timeout);
    client.state.thread_id = thread_id.clone();
    client.state.model = if options.model.is_empty() {
        extract_model(&thread_value).unwrap_or_default()
    } else {
        options.model.clone()
    };
    client.publish_live_metadata(
        resumed,
        resume_rejected,
        first_turn_timeout,
        semantic_timeout,
    );
    if !options.thread_name.trim().is_empty() {
        let _ = client
            .request(
                "thread/name/set",
                serde_json::json!({"threadId": thread_id.clone(), "name": options.thread_name.clone()}),
                handshake_timeout,
            )
            .await;
    }

    let input = codex_turn_input(
        &prompt,
        options.resume_expected,
        resumed,
        &options.resume_continuity_notice,
    );
    let mut turn_params = serde_json::json!({"threadId": thread_id, "input": input});
    apply_reasoning_effort(&mut turn_params, &options.thinking_level, true);
    apply_service_tier(&mut turn_params, &options.service_tier);
    client.notification_gate.arm();
    if let Err(error) = client
        .request("turn/start", turn_params, handshake_timeout)
        .await
    {
        return ProtocolOutcome {
            status: "failed".to_string(),
            error,
            session_id: client.state.thread_id,
            resumed,
            resume_rejected,
            ..ProtocolOutcome::default()
        };
    }
    if let Err(error) = client
        .wait_for_turn(
            options.semantic_inactivity_timeout,
            options.first_turn_no_progress_timeout,
        )
        .await
    {
        match error {
            TurnWaitError::Timeout {
                kind,
                timeout,
                last_activity,
            } => {
                let diagnostic = CodexTimeoutDiagnostic {
                    kind,
                    timeout,
                    last_activity,
                    thread_id: client.state.thread_id.clone(),
                    turn_id: client.state.turn_id.clone(),
                    model: configured_model(&client.state, &options),
                    ..CodexTimeoutDiagnostic::default()
                };
                let error = build_codex_timeout_diagnostic_error(&diagnostic, "");
                let session_id = client.state.thread_id.clone();
                let first_item_wait = client
                    .state
                    .first_item_wait_snapshot(first_turn_timeout, semantic_timeout);
                return ProtocolOutcome {
                    status: "timeout".to_string(),
                    error,
                    session_id,
                    resumed,
                    resume_rejected,
                    timeout_diagnostic: Some(diagnostic),
                    first_item_wait,
                    ..ProtocolOutcome::default()
                };
            }
            TurnWaitError::Protocol(error) => {
                client.finish_first_item_wait("protocol_error");
                let session_id = client.state.thread_id.clone();
                let first_item_wait = client
                    .state
                    .first_item_wait_snapshot(first_turn_timeout, semantic_timeout);
                return ProtocolOutcome {
                    status: "failed".to_string(),
                    error,
                    session_id,
                    resumed,
                    resume_rejected,
                    first_item_wait,
                    ..ProtocolOutcome::default()
                };
            }
            TurnWaitError::ProcessExit(error) => {
                client.finish_first_item_wait("process_exit");
                let session_id = client.state.thread_id.clone();
                let first_item_wait = client
                    .state
                    .first_item_wait_snapshot(first_turn_timeout, semantic_timeout);
                return ProtocolOutcome {
                    status: "failed".to_string(),
                    error,
                    session_id,
                    resumed,
                    resume_rejected,
                    first_item_wait,
                    ..ProtocolOutcome::default()
                };
            }
        }
    }
    let _ = client
        .drain_notifications(NOTIFICATION_QUIET, NOTIFICATION_DRAIN_MAX)
        .await;

    let state = client.state;
    let session_id = state.thread_id.clone();
    let first_item_wait = state.first_item_wait_snapshot(first_turn_timeout, semantic_timeout);
    let usage = usage_map(&state, &configured_model(&state, &options));
    let mut result = ProtocolOutcome {
        status: "completed".to_string(),
        output: if !state.final_answer.is_empty() {
            state.final_answer.clone()
        } else {
            state.last_agent_message.clone()
        },
        session_id,
        usage,
        resumed,
        resume_rejected,
        first_item_wait,
        ..ProtocolOutcome::default()
    };
    if let Some((status, error)) = codex_terminal_failure(&state) {
        result.status = status.to_string();
        result.error = error;
        result.output.clear();
    }
    result
}

fn codex_terminal_failure(state: &CodexState) -> Option<(&'static str, String)> {
    if state.turn_aborted {
        return Some((
            "aborted",
            if state.turn_error.is_empty() {
                "turn was aborted".to_string()
            } else {
                state.turn_error.clone()
            },
        ));
    }
    if !state.turn_error.is_empty() {
        return Some(("failed", state.turn_error.clone()));
    }
    if !state.turn_done {
        return Some(("failed", "codex turn ended without completion".to_string()));
    }
    None
}

async fn start_thread<R, W>(
    client: &mut CodexClient<R, W>,
    options: &ExecOptions,
    cwd: &str,
    handshake_timeout: Duration,
) -> Result<(String, bool, Value), String>
where
    R: AsyncBufRead + Unpin,
    W: AsyncWrite + Unpin,
{
    let mut params = serde_json::json!({
        "model": null,
        "modelProvider": null,
        "profile": null,
        "cwd": cwd,
        "approvalPolicy": null,
        "sandbox": null,
        "config": null,
        "baseInstructions": null,
        "developerInstructions": null,
        "compactPrompt": null,
        "includeApplyPatchTool": null,
        "experimentalRawEvents": false,
        "persistExtendedHistory": true,
    });
    if !options.model.is_empty() {
        params["model"] = Value::String(options.model.clone());
    }
    apply_reasoning_effort(&mut params, &options.thinking_level, false);
    apply_service_tier(&mut params, &options.service_tier);
    let value = client
        .request("thread/start", params, handshake_timeout)
        .await?;
    let thread_id = extract_thread_id(&value)
        .ok_or_else(|| "codex thread/start returned no thread ID".to_string())?;
    Ok((thread_id, false, value))
}

fn apply_reasoning_effort(params: &mut Value, level: &str, turn_start: bool) {
    if level.is_empty() {
        return;
    }
    if turn_start {
        params["effort"] = Value::String(level.to_string());
        return;
    }
    if !params["config"].is_object() {
        params["config"] = Value::Object(Map::new());
    }
    if let Some(config) = params["config"].as_object_mut() {
        config.insert(
            "model_reasoning_effort".to_string(),
            Value::String(level.to_string()),
        );
    }
}

fn apply_service_tier(params: &mut Value, tier: &str) {
    if !tier.is_empty() {
        params["serviceTier"] = Value::String(tier.to_string());
    }
}

fn codex_turn_input(
    prompt: &str,
    resume_expected: bool,
    resumed: bool,
    continuity_notice: &str,
) -> Vec<Value> {
    let text = if resume_expected && !resumed {
        format!("{continuity_notice}{prompt}")
    } else {
        prompt.to_string()
    };
    vec![serde_json::json!({"type":"text","text":text})]
}

struct CodexClient<R, W> {
    reader: AgentLineReader<R>,
    writer: W,
    next_id: u64,
    state: CodexState,
    messages: mpsc::Sender<Message>,
    notification_gate: CodexTurnNotificationGate,
    live_protocol: Option<Arc<Mutex<CodexLiveProtocol>>>,
    startup_stderr: Option<SharedDiagnosticBuffer>,
}

impl<R, W> CodexClient<R, W>
where
    R: AsyncBufRead + Unpin,
    W: AsyncWrite + Unpin,
{
    fn new(reader: R, writer: W, messages: mpsc::Sender<Message>) -> Self {
        Self {
            reader: AgentLineReader::new(reader),
            writer,
            next_id: 1,
            state: CodexState::default(),
            messages,
            notification_gate: CodexTurnNotificationGate::default(),
            live_protocol: None,
            startup_stderr: None,
        }
    }

    fn with_live_protocol(
        mut self,
        live_protocol: Arc<Mutex<CodexLiveProtocol>>,
        startup_stderr: SharedDiagnosticBuffer,
    ) -> Self {
        self.live_protocol = Some(live_protocol);
        self.startup_stderr = Some(startup_stderr);
        self
    }

    fn publish_live_state(&self) {
        let Some(live_protocol) = &self.live_protocol else {
            return;
        };
        if let Ok(mut live) = live_protocol.lock() {
            live.state = self.state.clone();
        }
    }

    fn publish_live_metadata(
        &self,
        resumed: bool,
        resume_rejected: bool,
        first_turn_timeout: Duration,
        semantic_inactivity_timeout: Duration,
    ) {
        let Some(live_protocol) = &self.live_protocol else {
            return;
        };
        if let Ok(mut live) = live_protocol.lock() {
            live.state = self.state.clone();
            live.resumed = resumed;
            live.resume_rejected = resume_rejected;
            live.first_turn_timeout = first_turn_timeout;
            live.semantic_inactivity_timeout = semantic_inactivity_timeout;
        }
    }

    fn finish_first_item_wait(&mut self, outcome: &str) {
        if self.state.first_item_wait_started.is_none()
            || !self.state.first_item_wait_outcome.is_empty()
        {
            return;
        }
        self.state.finish_first_item_wait(outcome);
        self.state.first_item_wait_stderr_classification = self
            .startup_stderr
            .as_ref()
            .map(|stderr| classify_codex_startup_stderr(&stderr.tail(), false))
            .unwrap_or_default();
        self.publish_live_state();
    }

    async fn request(
        &mut self,
        method: &str,
        params: Value,
        handshake_timeout: Duration,
    ) -> Result<Value, String> {
        let request = self.request_inner(method, params);
        match tokio::time::timeout(handshake_timeout, request).await {
            Ok(result) => result,
            Err(_) => Err(format!(
                "codex app-server handshake timeout: {method} did not respond after {}s",
                handshake_timeout.as_secs_f64()
            )),
        }
    }

    async fn request_inner(&mut self, method: &str, params: Value) -> Result<Value, String> {
        let id = self.next_id;
        self.next_id = self.next_id.saturating_add(1);
        self.write(&serde_json::json!({
            "jsonrpc":"2.0",
            "id":id,
            "method":method,
            "params":params,
        }))
        .await
        .map_err(|error| format!("write {method}: {error}"))?;

        loop {
            let line = self
                .reader
                .next_line()
                .await
                .map_err(|error| format!("codex stdout read failed: {error}"))?
                .ok_or_else(|| format!("codex app-server stream ended while awaiting {method}"))?;
            let Ok(frame) = serde_json::from_str::<Value>(line.trim()) else {
                continue;
            };
            let Some(object) = frame.as_object() else {
                continue;
            };
            let frame_id = object.get("id").and_then(Value::as_u64);
            if let (Some(frame_id), Some(agent_method)) =
                (frame_id, object.get("method").and_then(Value::as_str))
            {
                self.answer_server_request(frame_id, agent_method, object.get("params"))
                    .await?;
                continue;
            }
            if frame_id == Some(id) && object.get("method").is_none() {
                if let Some(error) = object.get("error") {
                    return Err(rpc_error(method, error));
                }
                return Ok(object.get("result").cloned().unwrap_or(Value::Null));
            }
            if frame_id.is_none() {
                if let Some(notification_method) = object.get("method").and_then(Value::as_str) {
                    self.handle_notification(notification_method, object.get("params"));
                }
            }
        }
    }

    async fn notify(&mut self, method: &str) -> Result<(), io::Error> {
        self.write(&serde_json::json!({"jsonrpc":"2.0","method":method}))
            .await
    }

    async fn drain_notifications(
        &mut self,
        quiet: Duration,
        maximum: Duration,
    ) -> Result<(), String> {
        let deadline = tokio::time::Instant::now() + maximum;
        loop {
            let remaining = deadline.saturating_duration_since(tokio::time::Instant::now());
            if remaining.is_zero() {
                return Ok(());
            }
            let wait = quiet.min(remaining);
            let line = tokio::select! {
                line = self.reader.next_line() => line.map_err(|error| error.to_string())?,
                () = tokio::time::sleep(wait) => return Ok(()),
            };
            let Some(line) = line else {
                return Ok(());
            };
            let Ok(frame) = serde_json::from_str::<Value>(line.trim()) else {
                continue;
            };
            let Some(object) = frame.as_object() else {
                continue;
            };
            if let (Some(id), Some(method)) = (
                object.get("id").and_then(Value::as_u64),
                object.get("method").and_then(Value::as_str),
            ) {
                self.answer_server_request(id, method, object.get("params"))
                    .await?;
            } else if object.get("id").is_none() {
                if let Some(method) = object.get("method").and_then(Value::as_str) {
                    self.handle_notification(method, object.get("params"));
                }
            }
        }
    }

    async fn wait_for_turn(
        &mut self,
        configured_semantic_timeout: Duration,
        configured_first_turn_timeout: Duration,
    ) -> Result<(), TurnWaitError> {
        let semantic_timeout = resolved_semantic_inactivity_timeout(configured_semantic_timeout);
        let first_turn_timeout =
            first_turn_no_progress_timeout(semantic_timeout, configured_first_turn_timeout);
        let mut semantic_deadline = tokio::time::Instant::now() + semantic_timeout;
        let mut first_turn_deadline = (self.state.turn_started
            && !self.state.first_turn_progress_observed)
            .then(|| tokio::time::Instant::now() + first_turn_timeout);
        let mut observed_activity_generation = self.state.activity_generation;
        let mut last_activity = if self.state.last_activity.is_empty() {
            "turn/start".to_string()
        } else {
            self.state.last_activity.clone()
        };

        while !self.state.turn_done {
            let now = tokio::time::Instant::now();
            let next_deadline = first_turn_deadline.map_or(semantic_deadline, |deadline| {
                deadline.min(semantic_deadline)
            });
            let sleep = tokio::time::sleep(next_deadline.saturating_duration_since(now));
            tokio::pin!(sleep);

            tokio::select! {
                line = self.reader.next_line() => {
                    let line = line
                        .map_err(|error| TurnWaitError::Protocol(format!("codex stdout read failed: {error}")))?
                        .ok_or_else(|| TurnWaitError::ProcessExit(
                            "codex app-server stream ended before turn completion".to_string(),
                        ))?;
                    let Ok(frame) = serde_json::from_str::<Value>(line.trim()) else {
                        continue;
                    };
                    let Some(object) = frame.as_object() else {
                        continue;
                    };
                    if let (Some(id), Some(method)) = (
                        object.get("id").and_then(Value::as_u64),
                        object.get("method").and_then(Value::as_str),
                    ) {
                        self.answer_server_request(id, method, object.get("params"))
                            .await
                            .map_err(TurnWaitError::Protocol)?;
                    } else if object.get("id").is_none() {
                        if let Some(method) = object.get("method").and_then(Value::as_str) {
                            self.handle_notification(method, object.get("params"));
                        }
                    }

                    if self.state.activity_generation != observed_activity_generation {
                        observed_activity_generation = self.state.activity_generation;
                        last_activity = self.state.last_activity.clone();
                        semantic_deadline = tokio::time::Instant::now() + semantic_timeout;
                        if self.state.first_turn_progress_observed {
                            first_turn_deadline = None;
                        } else if self.state.turn_started && first_turn_deadline.is_none() {
                            first_turn_deadline = Some(tokio::time::Instant::now() + first_turn_timeout);
                        }
                    }
                }
                () = &mut sleep => {
                    if self.state.turn_done {
                        continue;
                    }
                    let now = tokio::time::Instant::now();
                    if first_turn_deadline.is_some_and(|deadline| {
                        now >= deadline && deadline <= semantic_deadline
                    }) {
                        self.finish_first_item_wait("no_progress_timeout");
                        return Err(TurnWaitError::Timeout {
                            kind: CodexTimeoutKind::FirstTurnNoProgress,
                            timeout: first_turn_timeout,
                            last_activity,
                        });
                    }
                    if now >= semantic_deadline {
                        self.finish_first_item_wait("semantic_inactivity_timeout");
                        return Err(TurnWaitError::Timeout {
                            kind: CodexTimeoutKind::SemanticInactivity,
                            timeout: semantic_timeout,
                            last_activity,
                        });
                    }
                }
            }
        }
        Ok(())
    }

    async fn answer_server_request(
        &mut self,
        id: u64,
        method: &str,
        params: Option<&Value>,
    ) -> Result<(), String> {
        let result = match method {
            "item/commandExecution/requestApproval"
            | "execCommandApproval"
            | "item/fileChange/requestApproval"
            | "applyPatchApproval" => Some(serde_json::json!({"decision":"accept"})),
            "item/permissions/requestApproval" => Some(permission_response(params)),
            "mcpServer/elicitation/request" => {
                Some(serde_json::json!({"action":"accept","content":null,"_meta":null}))
            }
            _ => None,
        };
        if let Some(result) = result {
            self.write(&serde_json::json!({"jsonrpc":"2.0","id":id,"result":result}))
                .await
                .map_err(|error| error.to_string())
        } else {
            let error = format!("unsupported codex app-server request: {method}");
            self.state.set_error(&error);
            self.publish_live_state();
            self.write(&serde_json::json!({
                "jsonrpc":"2.0",
                "id":id,
                "error":{"code":-32601,"message":error},
            }))
            .await
            .map_err(|write_error| write_error.to_string())
        }
    }

    async fn write(&mut self, frame: &Value) -> Result<(), io::Error> {
        let mut encoded = serde_json::to_vec(frame)
            .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?;
        encoded.push(b'\n');
        self.writer.write_all(&encoded).await?;
        self.writer.flush().await
    }

    fn handle_notification(&mut self, method: &str, params: Option<&Value>) {
        let params = params.cloned().unwrap_or(Value::Null);
        if self.foreign_thread(&params) || !self.notification_gate.accept(method, &params) {
            return;
        }
        if method == "codex/event" || method.starts_with("codex/event/") {
            self.state.legacy = true;
            if let Some(message) = params.get("msg") {
                self.handle_legacy_event(message);
            }
            self.publish_live_state();
            return;
        }
        if self.state.legacy {
            return;
        }
        if matches!(
            method,
            "turn/started" | "turn/completed" | "error" | "thread/status/changed"
        ) || method.starts_with("item/")
        {
            self.handle_raw_notification(method, &params);
            self.publish_live_state();
        }
    }

    fn handle_legacy_event(&mut self, value: &Value) {
        let Some(event) = value.as_object() else {
            return;
        };
        match event
            .get("type")
            .and_then(Value::as_str)
            .unwrap_or_default()
        {
            "task_started" => {
                self.state.turn_started = true;
                self.state.start_first_item_wait();
                self.send(status_message("running", &self.state.thread_id));
            }
            "agent_message" => {
                if let Some(text) = event.get("message").and_then(Value::as_str) {
                    self.state.last_agent_message = text.to_string();
                    self.send(message(MessageType::Text, text));
                }
            }
            "exec_command_begin" => {
                let mut input = BTreeMap::new();
                if let Some(command) = event.get("command").and_then(Value::as_str) {
                    input.insert("command".to_string(), Value::String(command.to_string()));
                }
                self.send(tool_message(
                    MessageType::ToolUse,
                    event
                        .get("call_id")
                        .and_then(Value::as_str)
                        .unwrap_or_default(),
                    "exec_command",
                    input,
                    String::new(),
                ));
            }
            "exec_command_end" => self.send(tool_message(
                MessageType::ToolResult,
                event
                    .get("call_id")
                    .and_then(Value::as_str)
                    .unwrap_or_default(),
                "exec_command",
                BTreeMap::new(),
                event
                    .get("output")
                    .and_then(Value::as_str)
                    .unwrap_or_default()
                    .to_string(),
            )),
            "patch_apply_begin" => self.send(tool_message(
                MessageType::ToolUse,
                event
                    .get("call_id")
                    .and_then(Value::as_str)
                    .unwrap_or_default(),
                "patch_apply",
                patch_input(normalize_legacy_changes(event.get("changes"))),
                String::new(),
            )),
            "patch_apply_end" => {
                let changes = normalize_legacy_changes(event.get("changes"));
                let status = event
                    .get("status")
                    .and_then(Value::as_str)
                    .or_else(|| {
                        event.get("success").and_then(Value::as_bool).map(|ok| {
                            if ok {
                                "completed"
                            } else {
                                "failed"
                            }
                        })
                    })
                    .unwrap_or_default();
                let output = patch_result_output(
                    status,
                    changes.len(),
                    event
                        .get("stdout")
                        .and_then(Value::as_str)
                        .unwrap_or_default(),
                    event
                        .get("stderr")
                        .and_then(Value::as_str)
                        .unwrap_or_default(),
                );
                self.send(tool_message(
                    MessageType::ToolResult,
                    event
                        .get("call_id")
                        .and_then(Value::as_str)
                        .unwrap_or_default(),
                    "patch_apply",
                    BTreeMap::new(),
                    output,
                ));
            }
            "task_complete" => {
                self.state.merge_usage(event.get("usage"));
                self.finish_first_item_wait("turn_completed");
                self.state.turn_done = true;
            }
            "turn_aborted" => {
                self.state.turn_aborted = true;
                self.finish_first_item_wait("turn_aborted");
                self.state.turn_done = true;
            }
            _ => {}
        }
    }

    fn handle_raw_notification(&mut self, method: &str, params: &Value) {
        if self.foreign_thread(params) || self.foreign_turn(params) {
            return;
        }
        match method {
            "turn/started" => {
                self.state.turn_started = true;
                self.state.start_first_item_wait();
                if let Some(id) = nested_string(params, &["turn", "id"]) {
                    self.state.turn_id = id.to_string();
                }
                if let Some(id) = params.get("threadId").and_then(Value::as_str) {
                    self.state.thread_id = id.to_string();
                }
                self.send(status_message("running", &self.state.thread_id));
            }
            "turn/completed" => {
                let status = nested_string(params, &["turn", "status"]).unwrap_or_default();
                if status == "failed" {
                    let error = nested_string(params, &["turn", "error", "message"])
                        .unwrap_or("codex turn failed");
                    self.state.set_error(error);
                }
                if matches!(status, "cancelled" | "canceled" | "aborted" | "interrupted") {
                    self.state.turn_aborted = true;
                }
                if let Some(turn_id) = nested_string(params, &["turn", "id"]) {
                    if !self.state.completed_turns.insert(turn_id.to_string()) {
                        return;
                    }
                }
                self.state.merge_usage(params.get("turn"));
                let outcome = if self.state.turn_aborted {
                    "turn_aborted"
                } else if status == "failed" {
                    "turn_failed"
                } else {
                    "turn_completed"
                };
                self.finish_first_item_wait(outcome);
                self.state.turn_done = true;
            }
            "error" => {
                let will_retry = params
                    .get("willRetry")
                    .and_then(Value::as_bool)
                    .unwrap_or(false);
                if will_retry {
                    self.note_activity("error:retry");
                } else {
                    self.note_activity("error:terminal");
                    let error = nested_string(params, &["error", "message"])
                        .or_else(|| params.get("message").and_then(Value::as_str))
                        .unwrap_or("codex app-server error");
                    self.state.set_error(error);
                    self.state.turn_done = true;
                }
            }
            "thread/status/changed"
                if self.state.turn_started
                    && nested_string(params, &["status", "type"]) == Some("idle") =>
            {
                self.finish_first_item_wait("turn_completed");
                self.state.turn_done = true;
            }
            _ if method.starts_with("item/") => self.handle_item(method, params),
            _ => {}
        }
    }

    fn handle_item(&mut self, method: &str, params: &Value) {
        let item = params.get("item").and_then(Value::as_object);
        let item_type = item
            .and_then(|item| item.get("type"))
            .and_then(Value::as_str)
            .unwrap_or_default();
        let item_id = item
            .and_then(|item| item.get("id"))
            .and_then(Value::as_str)
            .unwrap_or_default();
        self.note_activity(&describe_item_activity(method, item_type, item_id));
        let Some(item) = item else {
            return;
        };
        match (method, item_type) {
            ("item/started", "commandExecution") => {
                let mut input = BTreeMap::new();
                if let Some(command) = item.get("command").and_then(Value::as_str) {
                    input.insert("command".to_string(), Value::String(command.to_string()));
                }
                self.send(tool_message(
                    MessageType::ToolUse,
                    item_id,
                    "exec_command",
                    input,
                    String::new(),
                ));
            }
            ("item/completed", "commandExecution") => self.send(tool_message(
                MessageType::ToolResult,
                item_id,
                "exec_command",
                BTreeMap::new(),
                item.get("aggregatedOutput")
                    .and_then(Value::as_str)
                    .unwrap_or_default()
                    .to_string(),
            )),
            ("item/started", "fileChange") => self.send(tool_message(
                MessageType::ToolUse,
                item_id,
                "patch_apply",
                patch_input(normalize_raw_changes(item.get("changes"))),
                String::new(),
            )),
            ("item/completed", "fileChange") => self.send(tool_message(
                MessageType::ToolResult,
                item_id,
                "patch_apply",
                BTreeMap::new(),
                patch_result_output(
                    item.get("status")
                        .and_then(Value::as_str)
                        .unwrap_or_default(),
                    normalize_raw_changes(item.get("changes")).len(),
                    "",
                    "",
                ),
            )),
            ("item/started", "mcpToolCall") => self.send(tool_message(
                MessageType::ToolUse,
                item_id,
                item.get("tool")
                    .and_then(Value::as_str)
                    .unwrap_or("mcp_tool"),
                mcp_input(item),
                String::new(),
            )),
            ("item/completed", "mcpToolCall") => {
                let status = item
                    .get("status")
                    .and_then(Value::as_str)
                    .unwrap_or("completed");
                let error = item
                    .get("error")
                    .and_then(|value| value.get("message"))
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                let output = if error.is_empty() {
                    status.to_string()
                } else {
                    format!("{status}\nerror: {}", sanitize_diagnostic(error))
                };
                self.send(tool_message_with_status(
                    item_id,
                    item.get("tool")
                        .and_then(Value::as_str)
                        .unwrap_or("mcp_tool"),
                    output,
                    normalize_status(status),
                ));
            }
            (_, "agentMessage") if method == "item/completed" => {
                if let Some(text) = item.get("text").and_then(Value::as_str) {
                    self.state.last_agent_message = text.to_string();
                    self.send(message(MessageType::Text, text));
                    if item.get("phase").and_then(Value::as_str) == Some("final_answer") {
                        self.state.final_answer = text.to_string();
                        if self.state.turn_started {
                            self.state.turn_done = true;
                        }
                    }
                }
            }
            (_, "reasoning") if method == "item/completed" => {
                if let Some(text) = item.get("text").and_then(Value::as_str) {
                    self.send(message(MessageType::Thinking, text));
                }
            }
            _ => {}
        }
    }

    fn foreign_thread(&self, params: &Value) -> bool {
        params
            .get("threadId")
            .and_then(Value::as_str)
            .is_some_and(|thread_id| {
                !self.state.thread_id.is_empty() && thread_id != self.state.thread_id
            })
    }

    fn foreign_turn(&self, params: &Value) -> bool {
        params
            .get("turnId")
            .and_then(Value::as_str)
            .is_some_and(|turn_id| !self.state.turn_id.is_empty() && turn_id != self.state.turn_id)
    }

    fn note_activity(&mut self, description: &str) {
        if description.is_empty() {
            return;
        }
        self.state.activity_generation = self.state.activity_generation.saturating_add(1);
        self.state.last_activity = description.to_string();
        if self.state.turn_started && is_first_turn_progress_activity(description) {
            if !self.state.first_turn_progress_observed {
                self.state.first_turn_progress_observed = true;
            }
            self.finish_first_item_wait(if description == "error:terminal" {
                "turn_failed"
            } else {
                "progress"
            });
        }
    }

    fn send(&mut self, value: Message) {
        self.note_activity(&describe_message_activity(&value));
        let _ = self.messages.try_send(value);
    }
}

#[derive(Debug, Default)]
struct CodexTurnNotificationGate {
    armed: bool,
    started: bool,
    turn_id: String,
}

impl CodexTurnNotificationGate {
    fn arm(&mut self) {
        self.armed = true;
        self.started = false;
        self.turn_id.clear();
    }

    fn accept(&mut self, method: &str, params: &Value) -> bool {
        if !self.armed {
            return false;
        }
        if method == "codex/event" || method.starts_with("codex/event/") {
            if nested_string(params, &["msg", "type"]) == Some("task_started") {
                self.started = true;
            }
            return true;
        }
        // ponytail: accept untagged post-arm events for legacy Codex streams;
        // tighten this only when every supported stream exposes a turn ID.
        match method {
            "turn/started" => {
                self.started = true;
                self.turn_id = nested_string(params, &["turn", "id"])
                    .unwrap_or_default()
                    .to_string();
                true
            }
            "turn/completed" if self.started => self.accepts_turn(params),
            "thread/status/changed" => !self.started || self.accepts_turn(params),
            method if method.starts_with("item/") => !self.started || self.accepts_turn(params),
            _ => true,
        }
    }

    fn accepts_turn(&self, params: &Value) -> bool {
        self.turn_id.is_empty()
            || nested_string(params, &["turnId"])
                .or_else(|| nested_string(params, &["turn", "id"]))
                .is_none_or(|turn_id| turn_id.is_empty() || turn_id == self.turn_id)
    }
}

