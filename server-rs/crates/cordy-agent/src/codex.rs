fn classify_retry_reason(
    result: &ProtocolOutcome,
    stderr: &str,
    cleanup_confirmed: bool,
) -> RetryReason {
    if !cleanup_confirmed {
        return RetryReason::None;
    }
    if is_initialize_timeout(&result.error) {
        return RetryReason::Initialize;
    }
    if result.status == "timeout"
        && result
            .error
            .starts_with(CODEX_FIRST_TURN_NO_PROGRESS_MARKER)
        && stderr
            .to_ascii_lowercase()
            .contains(MODEL_CATALOG_REFRESH_FAILURE_SIGNAL)
    {
        RetryReason::ModelCatalogRefresh
    } else {
        RetryReason::None
    }
}

fn retry_backoff(reason: RetryReason) -> Duration {
    match reason {
        RetryReason::Initialize => INITIALIZE_RETRY_BACKOFF,
        RetryReason::ModelCatalogRefresh => {
            let jitter_ms = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map(|duration| u64::from(duration.subsec_millis()))
                .unwrap_or_default();
            MODEL_CATALOG_RETRY_BACKOFF + Duration::from_millis(jitter_ms)
        }
        RetryReason::None => Duration::ZERO,
    }
}

