fn first_turn_no_progress_timeout(semantic_timeout: Duration, configured: Duration) -> Duration {
    if !configured.is_zero() {
        return configured;
    }
    if semantic_timeout.is_zero() || semantic_timeout > DEFAULT_FIRST_TURN_NO_PROGRESS_TIMEOUT {
        return DEFAULT_FIRST_TURN_NO_PROGRESS_TIMEOUT;
    }
    let scaled = semantic_timeout
        .checked_mul(4)
        .map(|value| value / 5)
        .unwrap_or(semantic_timeout);
    if scaled.is_zero() {
        semantic_timeout
    } else {
        scaled
    }
}

