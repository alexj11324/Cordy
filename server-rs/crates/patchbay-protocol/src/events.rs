// Chat events
pub const EVENT_CHAT_MESSAGE: &str = "chat:message";
pub const EVENT_CHAT_DONE: &str = "chat:done";
/// Supplements a finished turn with follow-up suggestions generated by the
/// post-completion pass. Sent after chat:done; clients that don't know it
/// simply never resolve the (equally unknown) pending state.
pub const EVENT_CHAT_QUICK_ACTIONS: &str = "chat:quick_actions";
/// Carries the deferred outcome of a cancelled chat task once the daemon has
/// flushed its Agent event history (or the sweeper grace period expired): either a
/// late "Stopped." assistant message or a draft restore (#5219). Channel
/// outbounds (Slack/Lark) deliberately do not subscribe to it — cancellation
/// stays silent on external channels.
pub const EVENT_CHAT_CANCEL_FINALIZED: &str = "chat:cancel_finalized";
pub const EVENT_CHAT_SESSION_READ: &str = "chat:session_read";
pub const EVENT_CHAT_SESSION_DELETED: &str = "chat:session_deleted";
pub const EVENT_CHAT_SESSION_UPDATED: &str = "chat:session_updated";

// In-app workspace channel events. These are workspace-scoped broadcasts;
// the payload contains the authoritative row so clients can invalidate or
// reconcile without treating external IM integrations as the same feature.
pub const EVENT_CHANNEL_CREATED: &str = "channel:created";
pub const EVENT_CHANNEL_MESSAGE_CREATED: &str = "channel:message";

// Project events
