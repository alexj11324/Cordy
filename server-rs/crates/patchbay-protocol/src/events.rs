pub const EVENT_AGENT_RESTORED: &str = "agent:restored";

// Task events (server <-> daemon). Each event maps to a status transition on
// agent_task_queue. Front-end subscribes by `task:` prefix and invalidates
// the workspace task snapshot, so the granularity here is "what does the user
// want to see change" — not "every internal status flip".
pub const EVENT_TASK_QUEUED: &str = "task:queued"; // ∅ → queued (enqueue / retry create)
pub const EVENT_TASK_DISPATCH: &str = "task:dispatch"; // queued → dispatched (daemon claim)
pub const EVENT_TASK_RUNNING: &str = "task:running"; // dispatched → running (daemon started)
pub const EVENT_TASK_WAITING_LOCAL_DIRECTORY: &str = "task:waiting_local_directory"; // dispatched → waiting_local_directory
pub const EVENT_TASK_PROGRESS: &str = "task:progress";
pub const EVENT_TASK_COMPLETED: &str = "task:completed"; // running → completed
pub const EVENT_TASK_FAILED: &str = "task:failed"; // running → failed
pub const EVENT_TASK_MESSAGE: &str = "task:message";
pub const EVENT_TASK_CANCELLED: &str = "task:cancelled"; // * → cancelled

