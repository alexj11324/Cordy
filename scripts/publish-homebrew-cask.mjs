#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const tapContentsUrl =
  "https://api.github.com/repos/alexj11324/homebrew-tap/contents/Casks/patchbay.rb";

function stableVersionParts(value) {
  const match = /^(?:v)?([0-9]+)\.([0-9]+)\.([0-9]+)$/u.exec(value);
  if (!match) {
    throw new Error(`expected a stable semantic version, got ${JSON.stringify(value)}`);
  }
  return {
    normalized: `${match[1]}.${match[2]}.${match[3]}`,
    parts: [BigInt(match[1]), BigInt(match[2]), BigInt(match[3])],
  };
}

export function compareStableVersions(candidate, current) {
  const left = stableVersionParts(candidate).parts;
  const right = stableVersionParts(current).parts;
  for (let index = 0; index < left.length; index += 1) {
    if (left[index] > right[index]) return 1;
    if (left[index] < right[index]) return -1;
  }
  return 0;
}

function caskVersion(content) {
  const match = /^\s*version "([^"]+)"\s*$/mu.exec(content);
  if (!match) throw new Error("generated Homebrew cask has no version stanza");
  return stableVersionParts(match[1]).normalized;
}

function decodeContent(payload) {
  if (payload?.encoding !== "base64" || typeof payload.content !== "string") {
    throw new Error("GitHub returned an invalid Homebrew cask payload");
  }
  return Buffer.from(payload.content.replace(/\s/gu, ""), "base64").toString(
    "utf8",
  );
}

async function responseError(response) {
  const body = (await response.text()).slice(0, 500);
  return new Error(
    `GitHub Homebrew tap request failed (${response.status}): ${body}`,
  );
}

export async function publishHomebrewCask({
  token,
  tag,
  caskContent,
  fetchImpl = fetch,
}) {
  if (!token) {
    throw new Error(
      "HOMEBREW_TAP_GITHUB_TOKEN is required to publish alexj11324/homebrew-tap",
    );
  }
  const candidateVersion = stableVersionParts(tag).normalized;
  const generatedVersion = caskVersion(caskContent);
  if (generatedVersion !== candidateVersion) {
    throw new Error(
      `generated cask version ${generatedVersion} does not match release ${candidateVersion}`,
    );
  }

  const headers = {
    accept: "application/vnd.github+json",
    authorization: `Bearer ${token}`,
    "user-agent": "patchbay-release",
    "x-github-api-version": "2022-11-28",
  };
  const currentResponse = await fetchImpl(`${tapContentsUrl}?ref=main`, {
    headers,
  });
  let current = null;
  if (currentResponse.status !== 404) {
    if (!currentResponse.ok) throw await responseError(currentResponse);
    const payload = await currentResponse.json();
    current = {
      sha: payload.sha,
      content: decodeContent(payload),
    };
    const currentVersion = caskVersion(current.content);
    const comparison = compareStableVersions(candidateVersion, currentVersion);
    if (comparison < 0) {
      throw new Error(
        `refusing to replace newer Homebrew cask ${currentVersion} with ${candidateVersion}`,
      );
    }
    if (comparison === 0) {
      if (current.content === caskContent) {
        return { status: "unchanged", version: candidateVersion };
      }
      throw new Error(
        `Homebrew cask ${candidateVersion} already exists, but the same version has different content`,
      );
    }
  }

  const body = {
    message: `Update Patchbay to ${tag}`,
    content: Buffer.from(caskContent, "utf8").toString("base64"),
    branch: "main",
    ...(current?.sha ? { sha: current.sha } : {}),
  };
  const updateResponse = await fetchImpl(tapContentsUrl, {
    method: "PUT",
    headers: { ...headers, "content-type": "application/json" },
    body: JSON.stringify(body),
  });
  if (!updateResponse.ok) throw await responseError(updateResponse);

  const verifyResponse = await fetchImpl(`${tapContentsUrl}?ref=main`, { headers });
  if (!verifyResponse.ok) throw await responseError(verifyResponse);
  const storedContent = decodeContent(await verifyResponse.json());
  if (storedContent !== caskContent) {
    throw new Error("published Homebrew cask does not match the generated bytes");
  }
  return { status: "updated", version: candidateVersion };
}

const directRun =
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (directRun) {
  try {
    const caskPath = process.env.CASK_PATH;
    if (!caskPath) throw new Error("CASK_PATH is required");
    const result = await publishHomebrewCask({
      token: process.env.GH_TOKEN,
      tag: process.env.TAG_NAME ?? "",
      caskContent: await readFile(caskPath, "utf8"),
    });
    console.log(`Homebrew cask ${result.status}: ${result.version}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`::error::${message}`);
    process.exitCode = 1;
  }
}
