func normalizeProjectMetadataIDs(raw []string, field string) ([]string, []pgtype.UUID, error) {
	ids := make([]string, 0, len(raw))
	uuidIDs := make([]pgtype.UUID, 0, len(raw))
	seen := make(map[string]struct{}, len(raw))
	for i, value := range raw {
		u, err := util.ParseUUID(strings.TrimSpace(value))
		if err != nil {
			return nil, nil, fmt.Errorf("%s[%d] must be a valid UUID", field, i)
		}
		canonical := uuidToString(u)
		if _, exists := seen[canonical]; exists {
			continue
		}
		seen[canonical] = struct{}{}
		ids = append(ids, canonical)
		uuidIDs = append(uuidIDs, u)
	}
	return ids, uuidIDs, nil
}

func normalizeProjectMilestones(raw []ProjectMilestone) ([]ProjectMilestone, error) {
	milestones := make([]ProjectMilestone, 0, len(raw))
	seen := make(map[string]struct{}, len(raw))
	for i, milestone := range raw {
		u, err := util.ParseUUID(strings.TrimSpace(milestone.ID))
		if err != nil {
			return nil, fmt.Errorf("milestones[%d].id must be a valid UUID", i)
		}
		id := uuidToString(u)
		if _, exists := seen[id]; exists {
			return nil, fmt.Errorf("milestones[%d].id is duplicated", i)
		}
		seen[id] = struct{}{}

		title := strings.TrimSpace(milestone.Title)
		if title == "" {
			return nil, fmt.Errorf("milestones[%d].title is required", i)
		}
		status := strings.TrimSpace(milestone.Status)
		if status == "" {
			status = "planned"
		}
		if status != "planned" && status != "completed" {
			return nil, fmt.Errorf("milestones[%d].status must be planned or completed", i)
		}

		var description *string
		if milestone.Description != nil {
			value := *milestone.Description
			description = &value
		}
		var dueDate *string
		if milestone.DueDate != nil && strings.TrimSpace(*milestone.DueDate) != "" {
			date, err := util.ParseCalendarDate(strings.TrimSpace(*milestone.DueDate))
			if err != nil {
				return nil, fmt.Errorf("milestones[%d].due_date must be YYYY-MM-DD", i)
			}
			value := date.Time.Format("2006-01-02")
			dueDate = &value
		}
		milestones = append(milestones, ProjectMilestone{
			ID: id, Title: title, Description: description, DueDate: dueDate, Status: status,
		})
	}
	return milestones, nil
}

func normalizeProjectMetadata(memberIDs, labelIDs, dependencyIDs []string, milestones []ProjectMilestone) (normalizedProjectMetadata, error) {
	members, memberUUIDs, err := normalizeProjectMetadataIDs(memberIDs, "member_ids")
	if err != nil {
		return normalizedProjectMetadata{}, projectMetadataError(err.Error())
	}
	labels, labelUUIDs, err := normalizeProjectMetadataIDs(labelIDs, "label_ids")
	if err != nil {
		return normalizedProjectMetadata{}, projectMetadataError(err.Error())
	}
	dependencies, dependencyUUIDs, err := normalizeProjectMetadataIDs(dependencyIDs, "dependency_ids")
	if err != nil {
		return normalizedProjectMetadata{}, projectMetadataError(err.Error())
	}
	normalizedMilestones, err := normalizeProjectMilestones(milestones)
	if err != nil {
		return normalizedProjectMetadata{}, projectMetadataError(err.Error())
	}
	return normalizedProjectMetadata{
		memberIDs: members, memberUUIDs: memberUUIDs,
		labelIDs: labels, labelUUIDs: labelUUIDs,
		dependencyIDs: dependencies, dependencyUUIDs: dependencyUUIDs,
		milestones: normalizedMilestones,
	}, nil
}

func projectMetadataJSON(metadata normalizedProjectMetadata) ([]byte, []byte, []byte, []byte, error) {
	memberIDs, err := json.Marshal(metadata.memberIDs)
	if err != nil {
		return nil, nil, nil, nil, err
	}
	labelIDs, err := json.Marshal(metadata.labelIDs)
	if err != nil {
		return nil, nil, nil, nil, err
	}
	dependencyIDs, err := json.Marshal(metadata.dependencyIDs)
	if err != nil {
		return nil, nil, nil, nil, err
	}
	milestones, err := json.Marshal(metadata.milestones)
	if err != nil {
		return nil, nil, nil, nil, err
	}
	return memberIDs, labelIDs, dependencyIDs, milestones, nil
}

func projectMetadataFieldsPresent(rawFields map[string]json.RawMessage) bool {
	for _, field := range []string{"member_ids", "label_ids", "dependency_ids", "milestones"} {
		if _, ok := rawFields[field]; ok {
			return true
		}
	}
	return false
}

func metadataFieldOrEmpty(rawFields map[string]json.RawMessage, field string, value *[]string) ([]string, bool) {
	if _, present := rawFields[field]; !present {
		return nil, false
	}
	if value == nil {
		return []string{}, true
	}
	return *value, true
}

func milestonesFieldOrEmpty(rawFields map[string]json.RawMessage, value *[]ProjectMilestone) ([]ProjectMilestone, bool) {
	if _, present := rawFields["milestones"]; !present {
		return nil, false
	}
	if value == nil {
		return []ProjectMilestone{}, true
	}
	return *value, true
}

func (h *Handler) validateProjectMetadata(ctx context.Context, q *db.Queries, workspaceID, projectID pgtype.UUID, metadata normalizedProjectMetadata) error {
	if len(metadata.memberUUIDs) > 0 {
		found, err := q.ListProjectMetadataMemberUsers(ctx, db.ListProjectMetadataMemberUsersParams{
			WorkspaceID: workspaceID, UserIds: metadata.memberUUIDs,
		})
		if err != nil {
			return err
		}
		if len(found) != len(metadata.memberUUIDs) {
			return projectMetadataError("member_ids contains a user who is not a member of this workspace")
		}
	}
	if len(metadata.labelUUIDs) > 0 {
		found, err := q.ListProjectMetadataLabels(ctx, db.ListProjectMetadataLabelsParams{
			WorkspaceID: workspaceID, LabelIds: metadata.labelUUIDs,
		})
		if err != nil {
			return err
		}
		if len(found) != len(metadata.labelUUIDs) {
			return projectMetadataError("label_ids contains a label that is not a project label in this workspace")
		}
	}
	if len(metadata.dependencyUUIDs) > 0 {
		if projectID.Valid {
			for _, dependencyID := range metadata.dependencyUUIDs {
				if dependencyID == projectID {
					return projectMetadataError("dependency_ids cannot contain the project itself")
				}
			}
		}
		found, err := q.ListProjectMetadataDependencies(ctx, db.ListProjectMetadataDependenciesParams{
			WorkspaceID: workspaceID, ProjectIds: metadata.dependencyUUIDs,
		})
		if err != nil {
			return err
		}
		if len(found) != len(metadata.dependencyUUIDs) {
			return projectMetadataError("dependency_ids contains a project outside this workspace")
		}
		dependencyJSON, err := json.Marshal(metadata.dependencyIDs)
		if err != nil {
			return err
		}
		cycle, err := q.ProjectMetadataDependencyCycle(ctx, db.ProjectMetadataDependencyCycleParams{
			WorkspaceID: workspaceID, SourceID: projectID, DependencyIds: dependencyJSON,
		})
		if err != nil {
			return err
		}
		if cycle {
			return projectMetadataError("dependency_ids would create a cycle")
		}
	}
	return nil
}

