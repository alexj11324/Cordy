type ProjectResponse struct {
	ID          string  `json:"id"`
	WorkspaceID string  `json:"workspace_id"`
	Title       string  `json:"title"`
	Summary     *string `json:"summary"`
	Description *string `json:"description"`
	Icon        *string `json:"icon"`
	Status      string  `json:"status"`
	Priority    string  `json:"priority"`
	LeadType    *string `json:"lead_type"`
	LeadID      *string `json:"lead_id"`
	// StartDate / DueDate are calendar days ("YYYY-MM-DD"), no time-of-day or
	// timezone — same contract as issue.start_date / issue.due_date.
	StartDate  *string `json:"start_date"`
	DueDate    *string `json:"due_date"`
	CreatedAt  string  `json:"created_at"`
	UpdatedAt  string  `json:"updated_at"`
	IssueCount int64   `json:"issue_count"`
	DoneCount  int64   `json:"done_count"`
	// ResourceCount is a breadcrumb pointing at the sub-collection at
	// /api/projects/{id}/resources. Resources themselves stay out of this
	// payload to keep parent metadata and child collections separate; clients
	// that need the list call ListProjectResources directly.
	ResourceCount int64              `json:"resource_count"`
	MemberIDs     []string           `json:"member_ids"`
	LabelIDs      []string           `json:"label_ids"`
	DependencyIDs []string           `json:"dependency_ids"`
	Milestones    []ProjectMilestone `json:"milestones"`
}

// ProjectMilestone is the durable, client-owned milestone shape. IDs are UUIDs
// generated by the client so an edit can replace one milestone without relying
// on a server-side positional identity.
type ProjectMilestone struct {
	ID          string  `json:"id"`
	Title       string  `json:"title"`
	Description *string `json:"description,omitempty"`
	DueDate     *string `json:"due_date,omitempty"`
	Status      string  `json:"status"`
}

type normalizedProjectMetadata struct {
	memberIDs       []string
	memberUUIDs     []pgtype.UUID
	labelIDs        []string
	labelUUIDs      []pgtype.UUID
	dependencyIDs   []string
	dependencyUUIDs []pgtype.UUID
	milestones      []ProjectMilestone
}

type projectMetadataValidationError struct{ message string }

func (e projectMetadataValidationError) Error() string { return e.message }

func isProjectMetadataValidationError(err error) bool {
	var target projectMetadataValidationError
	return errors.As(err, &target)
}

func projectMetadataError(message string) error {
	return projectMetadataValidationError{message: message}
}

func decodeProjectStringArray(raw []byte) []string {
	var ids []string
	if len(raw) == 0 || json.Unmarshal(raw, &ids) != nil || ids == nil {
		return []string{}
	}
	return ids
}

func decodeProjectMilestones(raw []byte) []ProjectMilestone {
	var milestones []ProjectMilestone
	if len(raw) == 0 || json.Unmarshal(raw, &milestones) != nil || milestones == nil {
		return []ProjectMilestone{}
	}
	return milestones
}

func projectMetadataFromDB(p db.Project) normalizedProjectMetadata {
	return normalizedProjectMetadata{
		memberIDs:     decodeProjectStringArray(p.MemberIds),
		labelIDs:      decodeProjectStringArray(p.LabelIds),
		dependencyIDs: decodeProjectStringArray(p.DependencyIds),
		milestones:    decodeProjectMilestones(p.Milestones),
	}
}

func projectToResponse(p db.Project) ProjectResponse {
	metadata := projectMetadataFromDB(p)
	return ProjectResponse{
		ID:            uuidToString(p.ID),
		WorkspaceID:   uuidToString(p.WorkspaceID),
		Title:         p.Title,
		Summary:       textToPtr(p.Summary),
		Description:   textToPtr(p.Description),
		Icon:          textToPtr(p.Icon),
		Status:        p.Status,
		Priority:      p.Priority,
		LeadType:      textToPtr(p.LeadType),
		LeadID:        uuidToPtr(p.LeadID),
		StartDate:     dateToPtr(p.StartDate),
		DueDate:       dateToPtr(p.DueDate),
		CreatedAt:     timestampToString(p.CreatedAt),
		UpdatedAt:     timestampToString(p.UpdatedAt),
		MemberIDs:     metadata.memberIDs,
		LabelIDs:      metadata.labelIDs,
		DependencyIDs: metadata.dependencyIDs,
		Milestones:    metadata.milestones,
	}
}

func (h *Handler) loadProjectIssueStats(ctx context.Context, workspaceID, projectID pgtype.UUID) (int64, int64) {
	terminalStatusKeys := h.projectTerminalIssueStatusKeys(ctx, workspaceID)
	stats, err := h.Queries.GetProjectIssueStats(ctx, db.GetProjectIssueStatsParams{
		WorkspaceID:        workspaceID,
		ProjectIds:         []pgtype.UUID{projectID},
		TerminalStatusKeys: terminalStatusKeys,
	})
	if err != nil || len(stats) == 0 {
		return 0, 0
	}
	return stats[0].TotalCount, stats[0].DoneCount
}

// projectTerminalIssueStatusKeys keeps project responses useful if the custom
// status catalog cannot be read. Canonical terminal keys are less complete
// than the workspace catalog, but they avoid rendering every project as 0/0.
func (h *Handler) projectTerminalIssueStatusKeys(ctx context.Context, workspaceID pgtype.UUID) []string {
	keys, err := h.terminalIssueStatusKeys(ctx, workspaceID)
	if err == nil {
		return keys
	}
	slog.Warn("expand project terminal status categories failed; using canonical keys",
		"workspace_id", uuidToString(workspaceID), "error", err)
	return []string{issuestatus.Done, issuestatus.Cancelled}
}

func (h *Handler) loadProjectResourceCount(ctx context.Context, projectID pgtype.UUID) int64 {
	rows, err := h.Queries.GetProjectResourceCounts(ctx, []pgtype.UUID{projectID})
	if err != nil || len(rows) == 0 {
		return 0
	}
	return rows[0].ResourceCount
}

